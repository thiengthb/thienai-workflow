#!/usr/bin/env node
// Checks that a pull request that is no longer a draft says how it was reviewed: a "## Review" section in its
// description with a filled "- Ai:" line or "- Bỏ qua: <lý do>" line (profile/REVIEW.md of thienai-workflow).
// Drafts and the AGENTS.md sync bot's PRs (branch chore/sync-agents-md) pass.
// Copy into scripts/ of a project and run it from a workflow like .github/workflows/review-check.yml.
// The check turns red; on a private repo without GitHub Pro it cannot block the merge button, so the rule is:
// nobody merges while it is red.
//
//   node templates/check-review.mjs                 # in GitHub Actions: reads the pull_request event ($GITHUB_EVENT_PATH)
//   node templates/check-review.mjs --body <file>   # check a description file by hand (treated as ready)
//
// Why: review in a session is a habit, and a habit written only in text gets skipped (STATUS grew back to
// 100 lines within an hour on sakubun, 2026-11-07). CI makes the step visible.
import { readFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SKIP_BRANCHES = ['chore/sync-agents-md'];
const TEMPLATE = 'mẫu ở profile/REVIEW.md của thienai-workflow';

/** The "## Review" section without comments and without the footer every AI PR ends with. null if missing. */
export function reviewSection(body) {
  const text = (body || '').replace(/\r\n/g, '\n');
  const m = /^##[ \t]+Review[ \t]*$/m.exec(text);
  if (!m) return null;
  let rest = text.slice(m.index + m[0].length).replace(/<!--[\s\S]*?-->/g, '');
  const stop = rest.search(/^(#{1,2}[ \t]|---[ \t]*$|https:\/\/claude\.ai\/code\/|_Generated by |🤖 Generated with )/m);
  return stop < 0 ? rest : rest.slice(0, stop);
}

/** Returns the problem in Vietnamese, or '' when the description is fine. */
export function checkReview(body, { draft = false, branch = '' } = {}) {
  if (draft || SKIP_BRANCHES.includes(branch)) return '';
  const section = reviewSection(body);
  if (section === null) return `Mô tả PR chưa có mục "## Review". Review rồi ghi kết quả vào mô tả (${TEMPLATE}), hoặc chuyển PR về nháp.`;
  const lines = section.split('\n').map((l) => l.trim()).filter(Boolean);
  const placeholder = lines.find((l) => /<[^<>/]{1,40}>/.test(l));
  if (placeholder) return `Mục "## Review" còn chỗ chưa điền: "${placeholder}".`;
  const filled = (label) => lines.some((l) => new RegExp(`^[-*][ \\t]+${label}:[ \\t]*\\S`).test(l));
  if (!filled('Ai') && !filled('Bỏ qua')) return `Mục "## Review" cần một dòng "- Ai: ..." (ai review, khi nào), hoặc "- Bỏ qua: <lý do>" (${TEMPLATE}).`;
  return '';
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  const bi = args.indexOf('--body');
  let body, draft = false, branch = '', label = 'PR';
  if (bi >= 0) {
    if (!args[bi + 1]) { console.error('Thiếu tên file sau --body.'); process.exit(2); }
    body = readFileSync(args[bi + 1], 'utf8');
  } else {
    const path = process.env.GITHUB_EVENT_PATH;
    if (!path) { console.error('Không có GITHUB_EVENT_PATH; chạy tay thì dùng --body <file>.'); process.exit(2); }
    const pr = JSON.parse(readFileSync(path, 'utf8')).pull_request;
    if (!pr) { console.log('Không phải sự kiện pull request, bỏ qua.'); process.exit(0); }
    body = pr.body; draft = !!pr.draft; branch = (pr.head && pr.head.ref) || ''; label = 'PR #' + pr.number;
  }
  const problem = checkReview(body, { draft, branch });
  if (problem) { console.error(`${label}: ${problem}`); process.exit(1); }
  console.log(draft ? `${label} còn nháp: chưa cần mục Review.` : SKIP_BRANCHES.includes(branch) ? `${label} do bot đồng bộ mở: bỏ qua.` : `${label} có mục Review: ổn.`);
}
